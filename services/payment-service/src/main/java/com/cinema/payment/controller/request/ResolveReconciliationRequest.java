package com.cinema.payment.controller.request;

import com.cinema.common.validation.annotation.UuidV7;
import com.cinema.payment.enums.ReconciliationResolution;

import io.swagger.v3.oas.annotations.media.Schema;

import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.NotNull;
import jakarta.validation.constraints.Size;

import java.util.UUID;

public record ResolveReconciliationRequest(
        @NotNull ReconciliationResolution resolution,
        @NotBlank @Size(max = 500) String reason,
        @Schema(
                        nullable = true,
                        description =
                                "Provider reference for a successful refund. "
                                        + "If omitted, the existing transaction reference is used.")
                @Size(max = 255)
                String providerReference,
        @Schema(nullable = true, description = "Required when resolution is REFUND_FAILED.")
                @Size(max = 100)
                String failureCode,
        @Size(max = 500) String failureMessage,
        @Schema(
                        nullable = true,
                        description =
                                "Optional UUID v7 correlation identifier. "
                                        + "Generated by the server when omitted.")
                @UuidV7
                UUID correlationId) {}
